import { randomBytes } from 'node:crypto';
import type { HTTPMethods } from 'fastify';
import { afterAll, afterEach, beforeAll, describe, expect, it } from 'vitest';
import { buildApp } from '../apps/server/src/app.js';
import type { AdminUser, Application, Dashboard, Tenant } from '../packages/contracts/src/index.js';
import { digest, openRepository, randomId, type Repository } from '../packages/storage/src/index.js';

// This suite requires the isolated PostgreSQL database supplied by CI/local verification.
const databaseUrl = process.env.SMART_FLINT_TEST_DATABASE_URL;
const issuer = 'https://admin-pg-identity.example';
const origin = 'https://admin-pg-flint.example';

describe.skipIf(!databaseUrl)('PostgreSQL administrative permissions across service instances', () => {
  let first: Repository;
  let second: Repository;
  let runtimeA: Awaited<ReturnType<typeof buildApp>> | undefined;
  let runtimeB: Awaited<ReturnType<typeof buildApp>> | undefined;
  let ownedSigningRecord: unknown;
  const records = new Map<string, Set<string>>();
  const userIds = new Set<string>();

  function own(collection: string, id: string) {
    const values = records.get(collection) ?? new Set<string>();
    values.add(id); records.set(collection, values);
  }

  beforeAll(async () => {
    first = await openRepository({ databaseUrl });
    second = await openRepository({ databaseUrl });
    // The global startup key cannot safely be opened using another test/deployment's encryption key.
    if (await first.get('secrets', 'bridge-signing')) throw new Error('Use a dedicated integration test database without a pre-existing runtime signing key.');
    const config = {
      demo: false, host: '127.0.0.1', port: 0, baseUrl: origin, consoleUrl: origin,
      adminToken: '', encryptionKey: randomBytes(32).toString('base64'), databaseUrl, sqlitePath: ':memory:',
      adminOidc: { issuer, clientId: 'admin-pg-client', authMethod: 'none' as const, allowedOrigins: [issuer], label: 'Test organization sign-in' },
    };
    runtimeA = await buildApp({ repository: first, seed: false, serveConsole: false, config });
    ownedSigningRecord = await first.get('secrets', 'bridge-signing');
    runtimeB = await buildApp({ repository: second, seed: false, serveConsole: false, config });
    await runtimeA.app.ready(); await runtimeB.app.ready();
  });

  afterEach(async () => {
    if (!first) return;
    // Audit IDs are random: identify only events generated by our known fixture actors/targets.
    for (const event of await first.list<{ id: string; actor?: { id: string }; resource?: { id: string } }>('events')) {
      if ((event.actor && userIds.has(event.actor.id)) || (event.resource && [...records.values()].some(ids => ids.has(event.resource!.id)))) await first.delete('events', event.id);
    }
    for (const [collection, ids] of records) for (const id of ids) await first.delete(collection, id);
    records.clear(); userIds.clear();
  });

  afterAll(async () => {
    await runtimeA?.app.close(); await runtimeB?.app.close();
    if (first) {
      if (ownedSigningRecord && JSON.stringify(await first.get('secrets', 'bridge-signing')) === JSON.stringify(ownedSigningRecord)) await first.delete('secrets', 'bridge-signing');
      await first.close();
    }
    if (second) await second.close();
  });

  async function user(role: AdminUser['role'], organizationIds: string[] = [], applicationIds: string[] = []) {
    const id = randomId('admin_pg_user');
    const timestamp = new Date().toISOString();
    const record: AdminUser = { id, issuer, subject: id, displayName: `PostgreSQL ${role}`, role, organizationIds, applicationIds, disabled: false, createdAt: timestamp, updatedAt: timestamp };
    await first.put('admin_users', record); own('admin_users', id); userIds.add(id);
    const credential = randomBytes(32).toString('base64url');
    const sessionId = `admin:${digest(credential)}`;
    await first.put('sessions', { id: sessionId, userId: id, kind: 'oidc', expiresAt: new Date(Date.now() + 3600_000).toISOString() });
    own('sessions', sessionId);
    return { record, headers: { cookie: `smart_flint_admin=${credential}`, origin, 'content-type': 'application/json' } };
  }

  async function request(runtime: NonNullable<typeof runtimeA>, identity: Awaited<ReturnType<typeof user>>, method: HTTPMethods, url: string, payload?: unknown) {
    return runtime.app.inject({ method, url, headers: identity.headers, ...(payload === undefined ? {} : { payload: JSON.stringify(payload) }) });
  }

  it('immediately applies API role, assignment and disablement changes on an independent service pool', async () => {
    const timestamp = new Date().toISOString();
    const orgA: Tenant = { id: randomId('admin_pg_org'), name: 'First test organization', slug: randomId('org').toLowerCase().replaceAll('_', '-'), createdAt: timestamp };
    const orgB: Tenant = { ...orgA, id: randomId('admin_pg_org'), name: 'Second test organization', slug: randomId('org').toLowerCase().replaceAll('_', '-') };
    const application = (name: string): Application => ({ id: randomId('admin_pg_app'), name, description: '', callbackUrls: [], requiredContext: [], requiredScopes: [], allowedModes: ['gateway'], createdAt: timestamp });
    const appA = application('First test application'), appB = application('Second test application');
    for (const organization of [orgA, orgB]) { await first.put('tenants', organization); own('tenants', organization.id); }
    for (const app of [appA, appB]) { await first.put('applications', app); own('applications', app.id); }
    const owner = await user('platform_admin');
    const operator = await user('integration_admin', [orgA.id], [appA.id]);

    const initial = await request(runtimeB!, operator, 'GET', '/api/admin/dashboard');
    expect(initial.statusCode, initial.body).toBe(200);
    expect(initial.json<Dashboard>().access?.identity.role).toBe('integration_admin');
    expect(initial.json<Dashboard>().applications.map(row => row.id)).toEqual([appA.id]);

    const change = await request(runtimeA!, owner, 'PATCH', `/api/admin/users/${operator.record.id}`, { role: 'viewer', organizationIds: [orgB.id], applicationIds: [appB.id] });
    expect(change.statusCode, change.body).toBe(200);
    const changed = await request(runtimeB!, operator, 'GET', '/api/admin/dashboard');
    expect(changed.statusCode, changed.body).toBe(200);
    const data = changed.json<Dashboard>();
    expect(data.access?.identity.role).toBe('viewer');
    expect(data.tenants.map(row => row.id)).toEqual([orgB.id]);
    expect(data.applications.map(row => row.id)).toEqual([appB.id]);
    const denied = await request(runtimeB!, operator, 'POST', `/api/admin/applications/${appB.id}/credentials`, {});
    expect(denied.statusCode, denied.body).toBe(403);

    const disable = await request(runtimeA!, owner, 'PATCH', `/api/admin/users/${operator.record.id}`, { disabled: true });
    expect(disable.statusCode, disable.body).toBe(200);
    expect((await request(runtimeB!, operator, 'GET', '/api/admin/dashboard')).statusCode).toBe(401);
    expect(await second.get<AdminUser>('admin_users', operator.record.id)).toMatchObject({ role: 'viewer', disabled: true, organizationIds: [orgB.id], applicationIds: [appB.id] });
    const events = (await second.list<{ action: string; actor?: { id: string }; resource?: { id: string } }>('events')).filter(row => row.action === 'admin.user_updated' && row.resource?.id === operator.record.id);
    expect(events).toHaveLength(2);
    expect(events.every(event => event.actor?.id === owner.record.id)).toBe(true);
  });

  it('serializes simultaneous final-owner disablement across instances and preserves one enabled owner', async () => {
    const existing = (await first.list<AdminUser>('admin_users')).filter(record => record.role === 'platform_admin' && !record.disabled);
    expect(existing, 'The final-owner race requires an isolated test database with no other administrators.').toEqual([]);
    const ownerA = await user('platform_admin'), ownerB = await user('platform_admin');
    const responses = await Promise.all([
      request(runtimeA!, ownerA, 'PATCH', `/api/admin/users/${ownerA.record.id}`, { disabled: true }),
      request(runtimeB!, ownerB, 'PATCH', `/api/admin/users/${ownerB.record.id}`, { disabled: true }),
    ]);
    expect(responses.map(response => response.statusCode).sort()).toEqual([200, 409]);
    expect(responses.find(response => response.statusCode === 409)?.json()).toMatchObject({ code: 'last_platform_admin' });
    const enabled = (await second.list<AdminUser>('admin_users')).filter(record => record.role === 'platform_admin' && !record.disabled);
    expect(enabled).toHaveLength(1);
    expect([ownerA.record.id, ownerB.record.id]).toContain(enabled[0]?.id);
  });
});
